// Helper function to get custom emoji by name
function getCustomEmoji(name) {
    return customEmojis[name] || `<:${name}:ID>`;
}

// Function to replace all emoji IDs with actual server IDs
function updateEmojiIds(serverEmojis) {
    const updatedEmojis = {};
    
    for (const [name, template] of Object.entries(customEmojis)) {
        // Try to find matching emoji in server
        const serverEmoji = serverEmojis.find(emoji => 
            emoji.name.toLowerCase().includes(name.toLowerCase()) ||
            name.toLowerCase().includes(emoji.name.toLowerCase())
        );
        
        if (serverEmoji) {
            updatedEmojis[name] = `<:${serverEmoji.name}:${serverEmoji.id}>`;
        } else {
            updatedEmojis[name] = template;
        }
    }
    
    return updatedEmojis;
}

